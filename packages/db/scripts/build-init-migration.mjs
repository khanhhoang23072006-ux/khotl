// Dựng migration đầu tiên = extension + DDL do Prisma sinh + phần SQL viết tay
// (tìm kiếm tiếng Việt, ràng buộc CHECK, trigger AuditLog).
// Chạy: pnpm --filter @khotl/db migration:init
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";

const generatedPath = "prisma/.init.generated.sql";
const migrationDir = "prisma/migrations/0001_init";

execFileSync(
  "prisma",
  [
    "migrate",
    "diff",
    "--from-empty",
    "--to-schema",
    "prisma/schema.prisma",
    "--script",
    "--output",
    generatedPath,
  ],
  { stdio: "inherit" },
);

const generated = readFileSync(generatedPath, "utf8");
const custom = readFileSync("prisma/sql/001_search_and_constraints.sql", "utf8");

const header = `-- Migration đầu tiên của Kho tài liệu HUST.
-- Phần 1: extension. Phần 2: DDL do \`prisma migrate diff\` sinh. Phần 3: SQL viết tay.

CREATE EXTENSION IF NOT EXISTS unaccent;
CREATE EXTENSION IF NOT EXISTS pg_trgm;
CREATE EXTENSION IF NOT EXISTS vector;

`;

mkdirSync(migrationDir, { recursive: true });
writeFileSync(`${migrationDir}/migration.sql`, `${header}${generated}\n\n${custom}`);
writeFileSync(
  "prisma/migrations/migration_lock.toml",
  '# Please do not edit this file manually\n# It should be added in your version-control system (e.g., Git)\nprovider = "postgresql"\n',
);
rmSync(generatedPath);
console.log(`Đã ghi ${migrationDir}/migration.sql`);
